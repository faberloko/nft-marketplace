import { expect, test, type Locator } from '@playwright/test'
import { ANA, BRUNO, fresh, label, login, mock, setScenarios } from './helpers'

async function fillWallet(form: Locator, data: Record<string, string>) {
  for (const [name, value] of Object.entries(data)) {
    const field = form.getByLabel(label(name))
    if (await field.evaluate((el) => el.tagName === 'SELECT')) await field.selectOption(value)
    else await field.fill(value)
  }
}
const WALLET = {
  'Nome de exibição': 'Bruno Lima', 'Apelido da carteira': 'Minha MetaMask', 'Rede': 'ethereum', 'Nome do perfil': 'brunolima',
  'Tipo de carteira': 'metamask', 'Código de indicação': 'KURIO2026', 'E-mail': 'bruno@nft.test', 'Nome ENS': 'bruno',
}

test.describe('sessão e conta', () => {
  test('cadastro com validação, conflito e sucesso', async ({ page }) => {
    await fresh(page, '/signup')
    const submit = page.getByRole('button', { name: /^Criar (conta|perfil)$/ })
    await submit.click()
    await expect(page.getByLabel('Nome de usuário')).toBeFocused()
    await expect(page.getByLabel('Nome de usuário')).toHaveAttribute('aria-invalid', 'true')
    await page.getByLabel('Nome de usuário').fill('carla')
    await page.getByLabel('E-mail').fill(ANA.email)
    await page.getByLabel('Senha', { exact: true }).fill('Senha@123')
    await page.getByLabel('Confirmar senha').fill('Senha@123')
    await submit.click()
    await expect(page.getByText('Este e-mail já está cadastrado.')).toBeVisible()
    await page.getByLabel('E-mail').fill('carla@nft.test')
    await submit.click()
    await expect(page).toHaveURL('/')
    await page.reload()
    await page.goto('/account/profile')
    await expect(page.getByLabel('Nome de usuário')).toHaveValue('carla')
  })

  test('login com erro, rota protegida e retorno ao fluxo', async ({ page }) => {
    await fresh(page, '/account/wallets')
    await expect(page).toHaveURL(/\/login\?redirect=/)
    await page.getByLabel('E-mail').fill(ANA.email)
    await page.getByLabel('Senha', { exact: true }).fill('errada')
    await page.getByRole('button', { name: 'Entrar', exact: true }).click()
    await expect(page.getByText('E-mail ou senha incorretos.')).toBeVisible()
    await page.getByLabel('Senha', { exact: true }).fill(ANA.password)
    await page.getByRole('button', { name: 'Entrar', exact: true }).click()
    await expect(page).toHaveURL('/account/wallets')
    await expect(page.getByRole('heading', { name: 'Carteira principal' })).toBeVisible()
  })

  test('expiração de sessão preserva o contexto e retoma após login', async ({ page }) => {
    await fresh(page)
    await login(page)
    await page.goto('/account/profile')
    await expect(page.getByLabel('Nome de exibição')).toHaveValue('Ana Souza')
    await mock(page, 'expire-sessions')
    await page.getByLabel('Apelido da carteira').fill('Nova')
    await page.getByRole('button', { name: 'Salvar', exact: true }).click()
    await expect(page).toHaveURL(/\/login\?redirect=%2Faccount%2Fprofile&reason=expired/)
    await expect(page.getByText('Sua sessão expirou')).toBeVisible()
    await page.getByLabel('E-mail').fill(ANA.email)
    await page.getByLabel('Senha', { exact: true }).fill(ANA.password)
    await page.getByRole('button', { name: 'Entrar', exact: true }).click()
    await expect(page).toHaveURL('/account/profile')
  })

  test('logout e troca de usuário não vazam dados privados', async ({ page }) => {
    await fresh(page)
    await login(page, ANA)
    await page.goto('/account/wallets')
    await expect(page.getByTestId('wallet-primary').getByLabel('Apelido da carteira')).toHaveValue('Principal')
    await page.getByRole('navigation', { name: 'Meu perfil' }).getByRole('button', { name: 'Sair' }).click()
    await expect(page).toHaveURL('/')
    await page.goto('/account/wallets')
    await expect(page).toHaveURL(/\/login/)
    await login(page, BRUNO, '/account/wallets')
    await expect(page).toHaveURL('/account/wallets')
    await expect(page.getByTestId('wallet-primary').getByLabel('Apelido da carteira')).toHaveValue('')
    await expect(page.getByText('Você ainda não adicionou uma carteira secundária.')).toBeVisible()
    await expect(page.locator('input[value="Reserva"]')).toHaveCount(0)
    // pedido de outro usuário não é acessível
    await page.goto('/orders/order-qualquer')
    await expect(page.getByRole('heading', { name: 'Pedido não encontrado' })).toBeVisible()
  })

  test('favoritos: otimista, falha com rollback e persistência', async ({ page }) => {
    await fresh(page)
    await login(page)
    await page.goto('/nft/nft-1')
    const fav = page.getByRole('button', { name: /^Favorit(ar|ado)$/ })
    await expect(fav).toHaveAttribute('aria-pressed', 'false')
    await setScenarios(page, ['instant', 'favorite-fail'])
    await fav.click()
    await expect(page.getByTestId('live-assertive')).toContainText('Não foi possível favoritar')
    await expect(fav).toHaveAttribute('aria-pressed', 'false')
    await setScenarios(page, ['instant'])
    await fav.click()
    await expect(fav).toHaveAttribute('aria-pressed', 'true')
    await page.reload()
    await expect(page.getByRole('button', { name: 'Favoritado' })).toHaveAttribute('aria-pressed', 'true')
    await page.goto('/favoritos')
    await expect(page.getByRole('heading', { name: 'Emerald Ape #042' })).toBeVisible()
  })

  test('perfil, avatar e senha com validações', async ({ page }) => {
    await fresh(page)
    await login(page)
    await page.goto('/account/profile')
    const save = page.getByRole('button', { name: 'Salvar', exact: true })
    await page.getByLabel('Nome de usuário').fill('Inválido!')
    await save.click()
    await expect(page.getByLabel('Nome de usuário')).toHaveAttribute('aria-invalid', 'true')
    await expect(page.getByLabel('Nome de usuário')).toBeFocused()
    await page.getByLabel('Nome de usuário').fill('brunolima') // conflito vindo da API
    await save.click()
    await expect(page.getByText('Este usuário já existe.')).toBeVisible()
    await page.getByLabel('Nome de usuário').fill('ana_nova')
    await page.getByLabel('Apelido da carteira').fill('Cofre')
    await save.click()
    await expect(page.getByText('✓ Alterações salvas.')).toBeVisible()

    const png = Buffer.from(await page.evaluate(() => { const c = document.createElement('canvas'); c.width = c.height = 64; const x = c.getContext('2d')!; x.fillStyle = '#D28A4C'; x.fillRect(0, 0, 64, 64); return c.toDataURL('image/png').split(',')[1] }), 'base64')
    await page.locator('#avatar-input').setInputFiles({ name: 'a.png', mimeType: 'image/png', buffer: png })
    await expect(page.getByTestId('avatar')).toHaveAttribute('src', /^data:image\/webp/)
    await page.locator('#avatar-input').setInputFiles({ name: 'a.gif', mimeType: 'image/gif', buffer: png })
    await expect(page.getByText('Formato não suportado.')).toBeVisible()
    await page.getByRole('button', { name: 'Remover' }).click()
    await expect(page.getByRole('img', { name: 'Sem avatar' })).toBeVisible()

    await page.getByLabel('Senha atual').fill('errada')
    await page.getByLabel('Nova senha', { exact: true }).fill('Nova@1234')
    await page.getByLabel('Confirmar nova senha').fill('Nova@1234')
    await save.click()
    await expect(page.locator('#pw-currentPassword-error')).toHaveText(/Senha atual incorreta/)
    await page.getByLabel('Senha atual').fill(ANA.password)
    await save.click()
    await expect(page.getByText('✓ Perfil e senha atualizados.')).toBeVisible()

    await page.reload()
    await expect(page.getByLabel('Nome de usuário')).toHaveValue('ana_nova')
    await expect(page.getByLabel('Apelido da carteira')).toHaveValue('Cofre')
  })

  test('carteiras: cadastro, edição e erros', async ({ page }) => {
    await fresh(page)
    await login(page, BRUNO)
    await page.goto('/account/wallets')
    const primary = page.getByTestId('wallet-primary')
    await primary.getByRole('button', { name: 'Salvar carteira' }).click()
    await expect(primary.getByLabel(label('Nome de exibição'))).toBeFocused()
    await fillWallet(primary, WALLET)
    await primary.getByLabel('Endereço da carteira').fill('0x123')
    await primary.getByRole('button', { name: 'Salvar carteira' }).click()
    await expect(primary.getByText(/0x seguido de 40/).last()).toBeVisible()
    await primary.getByLabel('Endereço da carteira').fill('0x' + 'a'.repeat(40))
    await primary.getByRole('button', { name: 'Salvar carteira' }).click()
    await expect(primary.getByText('✓ Carteira salva.')).toBeVisible()

    const secondary = page.getByTestId('wallet-secondary')
    await secondary.getByRole('button', { name: 'Adicionar' }).click()
    await fillWallet(secondary, { ...WALLET, 'Apelido da carteira': 'Reserva', 'Rede': 'polygon', 'Tipo de carteira': 'coinbase' })
    await secondary.getByLabel('Endereço da carteira').fill('0x' + 'A'.repeat(40)) // duplicado (case-insensitive)
    await secondary.getByRole('button', { name: 'Salvar carteira' }).click()
    await expect(secondary.getByText('Este endereço já está cadastrado.')).toBeVisible()
    await secondary.getByLabel('Endereço da carteira').fill('0x' + 'b'.repeat(40))
    await secondary.getByRole('button', { name: 'Salvar carteira' }).click()
    await expect(secondary.getByText('✓ Carteira salva.')).toBeVisible()

    await page.reload()
    await expect(page.getByTestId('wallet-primary').getByLabel('Apelido da carteira')).toHaveValue('Minha MetaMask')
    await page.getByTestId('wallet-primary').getByLabel('Apelido da carteira').fill('MetaMask editada')
    await page.getByTestId('wallet-primary').getByRole('button', { name: 'Salvar carteira' }).click()
    await expect(page.getByTestId('wallet-primary').getByText('✓ Carteira salva.')).toBeVisible()
  })
})
